    private void BPromedioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BPromedioActionPerformed
        String query = "SELECT CONCAT(mes, '/', año) AS periodo, glucosa_proom "
                + "FROM promedio_mensual "
                + "WHERE curp = 'ausl120130a'";

        datos = cnx.consultar(query);
        series.clear();
        series.add("totales");

        PGrafica.removeAll();
        PGrafica.setLayout(new java.awt.BorderLayout());
        chart = new GraficaXY("Promedio mensual de las mediciones de glucosa", "Promedio", "Glucosa", series, datos);
        chart.chartPanel.setPreferredSize(PGrafica.getSize());

        PGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        PGrafica.revalidate();
        PGrafica.updateUI();
        cnx.entablar(query, TConsulta);

    }//GEN-LAST:event_BPromedioActionPerformed

